ALTER TABLE public.user_account
 ADD COLUMN IF NOT EXISTS staff_password_hash VARCHAR(256)
 CHECK (staff_password_hash IS NULL OR employee_id IS NOT NULL);

ALTER TABLE public.material
 ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
 CHECK (status IN ('ACTIVE','INACTIVE'));

CREATE TABLE IF NOT EXISTS public.material_cost (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 material_id BIGINT NOT NULL REFERENCES public.material(material_id),
 unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
 effective_from DATE NOT NULL,
 effective_to DATE CHECK (effective_to > effective_from),
 CONSTRAINT material_cost_effective_excl
 EXCLUDE USING gist (material_id WITH =, daterange(effective_from,effective_to,'[)') WITH &&)
);

ALTER TABLE public.material_usage
 ADD COLUMN IF NOT EXISTS material_name_snapshot VARCHAR(140),
 ADD COLUMN IF NOT EXISTS unit_name_snapshot VARCHAR(50);

UPDATE public.material_usage AS usage
SET material_name_snapshot = COALESCE(usage.material_name_snapshot, material.material_name),
    unit_name_snapshot = COALESCE(usage.unit_name_snapshot, material.standard_unit)
FROM public.material AS material
WHERE material.material_id = usage.material_id
  AND (usage.material_name_snapshot IS NULL OR usage.unit_name_snapshot IS NULL);

