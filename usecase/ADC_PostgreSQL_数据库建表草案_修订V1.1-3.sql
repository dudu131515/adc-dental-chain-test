-- 公司基金计算校验示例（仅供D阶段设计论证，核算事务内执行）
-- incentive_fund = ROUND(GREATEST(net_profit,0)*0.10,2)
-- 不能据此计算个人奖金：用户未确认个人分配公式。
-- 注意：CHECK无法独自验证医生班次与诊所资源的跨表一致性、牙椅容量和汇总行金额；
-- 必须通过应用服务事务锁和多项测试进行维护，不能仅靠唯一索引。


-- 已确认业务统计口径（2026-11-19审核）
-- 一、正式预约按 slot_claim.start_at 所属的诊所本地日期纳入统计期：
--     排除未支付临时占位、诊所原因取消以及被改期替换的原时段；
--     纳入患者主动取消、到诊后实际开始诊疗、爽约、未履约未处置的正式预约。
-- 二、患者取消率 = 患者主动取消的正式预约数 / 统计期内应履约正式预约数。
--     实际就诊率 = 实际开始诊疗的正式预约数 / 同一分母；
--     诊所原因取消和爽约另列，改期原时段不计一次取消。
-- 三、爽约判定：当前时刻 > 预约结束时刻 + 15分钟、未实际开始诊疗、
--     未合法取消的预约；CHECK不能引用now()维护时效，应由定时事务更新状态并留痕。
-- 四、牙医季度绩效收入归属 Visit.ended_at（Asia/Shanghai本地季度），
--     不归属于开票时间issued_at或支付时间paid_at；待审批差额更正应追溯原Visit。
-- 五、允许确实开始诊疗后中止、无实际治疗的零金额主Invoice（此时invoice_line为零行）。
--     有正金额的行都必须有treatment_item_id；总额和行小计需同一事务核对。
-- 六、Appointment.deposit_id是跨改期不变的原预约金，Appointment.claim_id可指向新时段。
--     任何应用事务必须确保对应deposit_payment确实为PAID并与患者身份一致。
-- 七、建议为关键时段操作以clinic行锁串行化容量校验；排他约束防医生重叠，
--     但不能单靠EXCLUDE保证牙椅容量，且过期HOLD必须主动变为EXPIRED或RELEASED。
