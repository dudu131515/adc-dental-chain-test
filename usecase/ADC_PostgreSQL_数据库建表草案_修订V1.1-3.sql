-- 注意：表结构不是运行上线的保证。跨表一致性、并发容量、费用闭合须由应用事务及测试保证。
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE employee (
 employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_no VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 birth_date DATE, home_address TEXT, phone VARCHAR(40), email VARCHAR(120),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ON_LEAVE','INACTIVE'))
);
CREATE TABLE clinic (
 clinic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_no VARCHAR(40) NOT NULL UNIQUE, clinic_name VARCHAR(150) NOT NULL,
 postal_address TEXT NOT NULL, manager_id BIGINT REFERENCES employee(employee_id),
 phone VARCHAR(40), email VARCHAR(120), area_sqm NUMERIC(10,2) CHECK (area_sqm > 0),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE app_role (
 role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_code VARCHAR(50) NOT NULL UNIQUE, role_name VARCHAR(80) NOT NULL
);
CREATE TABLE employee_role (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employee(employee_id),
 role_id BIGINT NOT NULL REFERENCES app_role(role_id),
 scope_clinic_id BIGINT REFERENCES clinic(clinic_id),
 UNIQUE (employee_id,role_id,scope_clinic_id)
);
CREATE TABLE qualification (
 qualification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 qualification_code VARCHAR(50) UNIQUE NOT NULL, qualification_name VARCHAR(120) NOT NULL
);
CREATE TABLE employee_qualification (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES employee(employee_id),
 qualification_id BIGINT NOT NULL REFERENCES qualification(qualification_id),
 certificate_no VARCHAR(80), valid_from DATE, valid_until DATE,
 CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);
CREATE TABLE shift_demand (
 demand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 required_qualification_id BIGINT REFERENCES qualification(qualification_id),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 required_count INTEGER NOT NULL DEFAULT 1 CHECK (required_count>0),
 status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
 CHECK (start_at<end_at)
);
CREATE TABLE shift (
 shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 demand_id BIGINT REFERENCES shift_demand(demand_id),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PENDING','ACCEPTED','REJECTED','PUBLISHED','CANCELLED')),
 doctor_response_at TIMESTAMPTZ, published_at TIMESTAMPTZ,
 CHECK (start_at<end_at),
 EXCLUDE USING gist (dentist_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&)
  WHERE (status='PUBLISHED')
);
CREATE TABLE dental_chair (
 chair_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 chair_no VARCHAR(40) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
 UNIQUE(clinic_id,chair_no)
);
CREATE TABLE patient (
 patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_no VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL, birth_date DATE NOT NULL,
 billing_address TEXT NOT NULL, phone VARCHAR(40) NOT NULL,
 email VARCHAR(120), emergency_name VARCHAR(100) NOT NULL, emergency_phone VARCHAR(40) NOT NULL
);
CREATE TABLE patient_allergy (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patient(patient_id),
 allergen_name VARCHAR(120) NOT NULL, notes TEXT,
 UNIQUE(patient_id,allergen_name)
);
CREATE TABLE slot_claim (
 claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patient(patient_id),
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 shift_id BIGINT NOT NULL REFERENCES shift(shift_id),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 expires_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL CHECK(status IN ('HOLD','CONFIRMED','EXPIRED','RELEASED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(start_at<end_at),
 CHECK(status <> 'HOLD' OR expires_at IS NOT NULL),
 EXCLUDE USING gist (dentist_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&)
  WHERE (status IN ('HOLD','CONFIRMED'))
);
CREATE TABLE deposit_payment (
 deposit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 claim_id BIGINT NOT NULL UNIQUE REFERENCES slot_claim(claim_id),
 amount NUMERIC(12,2) NOT NULL DEFAULT 50.00 CHECK(amount>=0),
 status VARCHAR(30) NOT NULL CHECK(status IN ('PENDING','PAID','FAILED')),
 payment_token VARCHAR(100) UNIQUE,
 paid_at TIMESTAMPTZ
);
CREATE TABLE appointment (
 appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_no VARCHAR(50) NOT NULL UNIQUE,
 claim_id BIGINT NOT NULL UNIQUE REFERENCES slot_claim(claim_id),
 deposit_id BIGINT NOT NULL UNIQUE REFERENCES deposit_payment(deposit_id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CHECKED_IN','IN_TREATMENT','COMPLETED','CANCELLED','NO_SHOW')),
 is_attended BOOLEAN NOT NULL DEFAULT FALSE,
 planned_treatment_note TEXT, special_requirement TEXT,
 confirmed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (NOT is_attended OR status IN ('IN_TREATMENT','COMPLETED'))
);
CREATE TABLE appointment_change (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES appointment(appointment_id),
 change_type VARCHAR(30) NOT NULL CHECK(change_type IN ('RESCHEDULE','CANCEL','NO_SHOW')),
 cancel_party VARCHAR(16) CHECK(cancel_party IN ('PATIENT','CLINIC')),
 old_claim_id BIGINT REFERENCES slot_claim(claim_id),
 new_claim_id BIGINT REFERENCES slot_claim(claim_id),
 reason TEXT, changed_by BIGINT REFERENCES employee(employee_id),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((change_type='CANCEL' AND cancel_party IS NOT NULL) OR (change_type <> 'CANCEL' AND cancel_party IS NULL))
);
CREATE TABLE deposit_refund (
 refund_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 deposit_id BIGINT NOT NULL REFERENCES deposit_payment(deposit_id),
 refund_amount NUMERIC(12,2) NOT NULL CHECK(refund_amount>=0),
 reason VARCHAR(60) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK(status IN ('PENDING','SUCCEEDED','FAILED','RETAINED')),
 idempotency_key VARCHAR(100) NOT NULL UNIQUE,
 requested_at TIMESTAMPTZ NOT NULL DEFAULT now(), completed_at TIMESTAMPTZ
);
CREATE TABLE visit (
 visit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointment(appointment_id),
 main_dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 started_at TIMESTAMPTZ NOT NULL, ended_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL CHECK(status IN ('IN_PROGRESS','COMPLETED','TERMINATED')),
 clinical_notes TEXT, termination_reason TEXT,
 CHECK(ended_at IS NULL OR ended_at>=started_at)
);
CREATE TABLE chair_usage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES appointment(appointment_id),
 chair_id BIGINT NOT NULL REFERENCES dental_chair(chair_id),
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(), released_at TIMESTAMPTZ,
 CHECK(released_at IS NULL OR released_at>=assigned_at)
);
CREATE TABLE dentist_work_session (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 visit_id BIGINT NOT NULL REFERENCES visit(visit_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 started_at TIMESTAMPTZ NOT NULL, ended_at TIMESTAMPTZ NOT NULL,
 duration_minutes NUMERIC(12,2) NOT NULL CHECK(duration_minutes>=0),
 CHECK(ended_at>=started_at),
 CHECK(duration_minutes=ROUND(EXTRACT(EPOCH FROM (ended_at-started_at))/60.0,2))
);
CREATE TABLE treatment_type (
 treatment_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treatment_code VARCHAR(50) NOT NULL UNIQUE,
 treatment_name VARCHAR(160) NOT NULL, standard_unit VARCHAR(50) NOT NULL,
 required_qualification_id BIGINT REFERENCES qualification(qualification_id),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE treatment_price (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treatment_type_id BIGINT NOT NULL REFERENCES treatment_type(treatment_type_id),
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0),
 effective_from DATE NOT NULL, effective_to DATE,
 UNIQUE(treatment_type_id,effective_from),
 CHECK(effective_to IS NULL OR effective_to>effective_from)
);
CREATE TABLE treatment_item (
 item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 visit_id BIGINT NOT NULL REFERENCES visit(visit_id),
 treatment_type_id BIGINT NOT NULL REFERENCES treatment_type(treatment_type_id),
 performing_dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 tooth_code VARCHAR(20), units NUMERIC(12,3) NOT NULL CHECK(units>0),
 unit_name_snapshot VARCHAR(50) NOT NULL,
 unit_price_snapshot NUMERIC(12,2) NOT NULL CHECK(unit_price_snapshot>=0),
 amount NUMERIC(14,2) NOT NULL CHECK(amount>=0),
 patient_consented BOOLEAN NOT NULL DEFAULT FALSE,
 recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE material (
 material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 material_code VARCHAR(40) NOT NULL UNIQUE,
 material_name VARCHAR(140) NOT NULL, standard_unit VARCHAR(50) NOT NULL
);
CREATE TABLE material_usage (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treatment_item_id BIGINT NOT NULL REFERENCES treatment_item(item_id),
 material_id BIGINT NOT NULL REFERENCES material(material_id),
 quantity NUMERIC(12,3) NOT NULL CHECK(quantity>=0),
 unit_cost_snapshot NUMERIC(12,2) NOT NULL CHECK(unit_cost_snapshot>=0)
);
CREATE TABLE invoice (
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_no VARCHAR(50) NOT NULL UNIQUE,
 visit_id BIGINT NOT NULL UNIQUE REFERENCES visit(visit_id),
 original_total NUMERIC(14,2) NOT NULL CHECK(original_total>=0),
 status VARCHAR(24) NOT NULL CHECK(status IN ('ISSUED','PART_PAID','SETTLED','VOIDED')),
 issued_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE invoice_line (
 line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES invoice(invoice_id),
 treatment_item_id BIGINT NOT NULL UNIQUE REFERENCES treatment_item(item_id),
 treatment_name_snapshot VARCHAR(160) NOT NULL,
 unit_name_snapshot VARCHAR(50) NOT NULL,
 units NUMERIC(12,3) NOT NULL CHECK(units>0),
 unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0),
 subtotal NUMERIC(14,2) NOT NULL CHECK(subtotal>=0)
);
CREATE TABLE invoice_payment (
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES invoice(invoice_id),
 payment_kind VARCHAR(12) NOT NULL CHECK(payment_kind IN ('PAYMENT','REFUND')),
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','SUCCEEDED','FAILED')),
 paid_at TIMESTAMPTZ, idempotency_key VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE performance_period (
 period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 perf_year INTEGER NOT NULL CHECK(perf_year>=2020),
 perf_quarter INTEGER NOT NULL CHECK(perf_quarter BETWEEN 1 AND 4),
 status VARCHAR(20) NOT NULL CHECK(status IN ('OPEN','CALCULATING','NEEDS_DATA','REVIEW','CONFIRMED')),
 UNIQUE(perf_year,perf_quarter)
);
CREATE TABLE operating_expense (
 expense_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 period_id BIGINT NOT NULL REFERENCES performance_period(period_id),
 expense_category VARCHAR(100) NOT NULL,
 amount NUMERIC(14,2) NOT NULL CHECK(amount>=0),
 scope VARCHAR(20) NOT NULL CHECK(scope IN ('DIRECT','SHARED')),
 dentist_id BIGINT REFERENCES employee(employee_id),
 CHECK((scope='SHARED' AND dentist_id IS NULL) OR (scope='DIRECT' AND dentist_id IS NOT NULL))
);
CREATE TABLE expense_allocation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 expense_id BIGINT NOT NULL REFERENCES operating_expense(expense_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 allocated_amount NUMERIC(14,2) NOT NULL CHECK(allocated_amount>=0),
 basis_minutes NUMERIC(12,2) CHECK(basis_minutes>=0),
 UNIQUE(expense_id,dentist_id)
);
CREATE TABLE dentist_performance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_id BIGINT NOT NULL REFERENCES performance_period(period_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 revenue NUMERIC(14,2) NOT NULL DEFAULT 0,
 material_cost NUMERIC(14,2) NOT NULL DEFAULT 0,
 operating_cost NUMERIC(14,2) NOT NULL DEFAULT 0,
 net_profit NUMERIC(14,2) NOT NULL DEFAULT 0,
 UNIQUE(period_id,dentist_id,clinic_id)
);
CREATE TABLE company_performance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_id BIGINT NOT NULL UNIQUE REFERENCES performance_period(period_id),
 revenue NUMERIC(16,2) NOT NULL DEFAULT 0,
 material_cost NUMERIC(16,2) NOT NULL DEFAULT 0,
 operating_cost NUMERIC(16,2) NOT NULL DEFAULT 0,
 net_profit NUMERIC(16,2) NOT NULL DEFAULT 0,
 incentive_fund NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK(incentive_fund>=0),
 CHECK (incentive_fund=ROUND(GREATEST(net_profit,0)*0.10,2)),
 calculated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE treatment_correction (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 visit_id BIGINT NOT NULL REFERENCES visit(visit_id),
 requested_by BIGINT NOT NULL REFERENCES employee(employee_id),
 reason TEXT NOT NULL, proposed_changes JSONB NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','APPLIED')),
 requested_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE correction_approval (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 correction_id BIGINT NOT NULL UNIQUE REFERENCES treatment_correction(id),
 reviewer_id BIGINT NOT NULL REFERENCES employee(employee_id),
 decision VARCHAR(15) NOT NULL CHECK(decision IN ('APPROVED','REJECTED')),
 reason TEXT, decided_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE invoice_adjustment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES invoice(invoice_id),
 correction_id BIGINT NOT NULL UNIQUE REFERENCES treatment_correction(id),
 signed_amount NUMERIC(14,2) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE user_account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT UNIQUE REFERENCES patient(patient_id),
 employee_id BIGINT UNIQUE REFERENCES employee(employee_id),
 login_identity VARCHAR(180) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
 CHECK ((patient_id IS NOT NULL)::INTEGER + (employee_id IS NOT NULL)::INTEGER = 1)
);
CREATE TABLE audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT REFERENCES user_account(id),
 action VARCHAR(80) NOT NULL, target_type VARCHAR(80) NOT NULL,
 target_id BIGINT, before_value JSONB, after_value JSONB,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE appointment_requested_treatment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES appointment(appointment_id),
 treatment_type_id BIGINT NOT NULL REFERENCES treatment_type(treatment_type_id),
 notes TEXT, UNIQUE(appointment_id,treatment_type_id)
);
