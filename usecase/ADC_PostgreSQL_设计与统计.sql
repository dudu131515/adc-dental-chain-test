CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE employee (
 employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_no VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(100) NOT NULL,
 birth_date DATE, home_address TEXT, phone VARCHAR(40), email VARCHAR(120),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','ON_LEAVE','INACTIVE'))
);
CREATE TABLE clinic (
 clinic_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_no VARCHAR(40) NOT NULL UNIQUE, clinic_name VARCHAR(150) NOT NULL,
 postal_address TEXT NOT NULL, manager_id BIGINT REFERENCES employee(employee_id),
 phone VARCHAR(40), email VARCHAR(120), area_sqm NUMERIC(10,2) CHECK (area_sqm > 0),
 status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);
-- Apply as the ADC business schema owner. Existing employees remain available for verified entry of their profiles.
