CREATE TABLE shift_demand (
 demand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 required_qualification_id BIGINT REFERENCES qualification(qualification_id),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 required_count INTEGER NOT NULL DEFAULT 1 CHECK (required_count>0),
 status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
 CHECK (start_at<end_at)
);
CREATE TABLE shift (
 shift_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 demand_id BIGINT REFERENCES shift_demand(demand_id),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PENDING','ACCEPTED','REJECTED','PUBLISHED','CANCELLED')),
 doctor_response_at TIMESTAMPTZ, published_at TIMESTAMPTZ,
 CHECK (start_at<end_at),
 EXCLUDE USING gist (dentist_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&)
  WHERE (status='PUBLISHED')
);
CREATE TABLE dental_chair (
 chair_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 chair_no VARCHAR(40) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
 chair_kind VARCHAR(40) NOT NULL DEFAULT 'GENERAL' CHECK (btrim(chair_kind) <> ''),
