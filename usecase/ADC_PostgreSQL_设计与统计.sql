CREATE TABLE appointment_change (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES appointment(appointment_id),
 change_type VARCHAR(30) NOT NULL CHECK(change_type IN ('RESCHEDULE','CANCEL','NO_SHOW')),
 cancel_party VARCHAR(16) CHECK(cancel_party IN ('PATIENT','CLINIC')),
 old_claim_id BIGINT REFERENCES slot_claim(claim_id),
 new_claim_id BIGINT REFERENCES slot_claim(claim_id),
 reason TEXT, changed_by BIGINT REFERENCES employee(employee_id),
 changed_by_patient_id BIGINT REFERENCES patient(patient_id),
 changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((change_type='CANCEL' AND cancel_party IS NOT NULL) OR (change_type <> 'CANCEL' AND cancel_party IS NULL)),
 CHECK (num_nonnulls(changed_by, changed_by_patient_id) <= 1),
 CHECK (change_type<>'NO_SHOW' OR changed_by IS NOT NULL),
 CHECK ((change_type='RESCHEDULE' AND old_claim_id IS NOT NULL AND new_claim_id IS NOT NULL AND old_claim_id<>new_claim_id)
        OR (change_type<>'RESCHEDULE' AND new_claim_id IS NULL))
);
CREATE TABLE deposit_refund (
