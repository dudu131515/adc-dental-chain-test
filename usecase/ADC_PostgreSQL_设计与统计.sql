-- PostgreSQL 15+（UNIQUE NULLS NOT DISTINCT）；需要 btree_gist。
-- 实现职责：按诊所 ID 升序锁定 clinic 行，实现涉及多店的预约、改期、释放的容量串行化。
-- 先清理到期 HOLD。普通项目取默认时长，缺省时由牙医估时并由前台登记。
-- 占位保存主预约项目和所需牙椅类别快照，其他项目由 appointment_requested_treatment 保存。
-- 在同一锁协议中确认已发布班次、牙医资格和预约全程牙椅容量。纳入有效 HOLD、CONFIRMED、
-- 椅类别与停用区间，按可用牙椅判断整段分配可行性；到诊核验后才分配具体牙椅。
-- 改期截止按原预约诊所核准工作日历，取前一工作日中国本地 20:00。
-- 同一预约改期时，按上述规则锁住涉及的诊所并校验新资源，只将本预约的旧占位视为可替换。
-- 新旧占位重叠时，在改期事务内执行 SET CONSTRAINTS slot_claim_dentist_time_excl DEFERRED。
-- 新占位成功后更新预约引用并释放旧占位，提交前执行 SET CONSTRAINTS slot_claim_dentist_time_excl IMMEDIATE。
-- 排斥检查失败时回滚此次改期，保留原预约、占位和预约金。
-- 发布及变更牙医异店相邻班次时，由服务保证两段之间至少 60 分钟。
-- 预约金初次支付须与原占位、患者一致；改期后的当前占位可不同，原 deposit_id 不变。
-- 模拟回执按 payment_token 去重。迟到成功回执只记录退款义务，不创建正式预约。
-- 合法取消、改期、开始诊疗、退款义务和临床更正由各自事务保证跨表一致性。
-- 授权前台在预约时段结束时点或之后核实未到诊、未取消且无诊所原因时，可人工确认爽约。
-- 已签到未接诊交前台核实。服务在同一事务写入状态、appointment_change 与 audit_log 并登记资金处理。
-- 同一治疗项和 Invoice 需属于同一 Visit；原始单据、批准差额和实际诊疗资金分别记账。
-- 每项共同费用等于各牙医分摊加未分配余额；公司费用含未分配余额。
-- 财务更正通过已批准的临床更正、差额和对应收退款处理。全额冲销保留主单和状态模型，
-- 追加使应计金额归零的差额，并按实收净额办理应退资金。差额归属原 Visit 结束季度。
-- 已确认季度保留原版和各历史结果。应用串行分配新版号，按已批准差额生成新快照，
-- 由授权人员确认，并校验归属季度、来源差额及旧版不可覆盖。报表可比较原版与更正版。
-- 本脚本定义数据库结构。Django 应用服务、回执通道和自动任务属于报告设计。
