CREATE TABLE slot_claim (
 claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES patient(patient_id),
 clinic_id BIGINT NOT NULL REFERENCES clinic(clinic_id),
 dentist_id BIGINT NOT NULL REFERENCES employee(employee_id),
 shift_id BIGINT NOT NULL REFERENCES shift(shift_id),
 requested_treatment_type_id BIGINT NOT NULL REFERENCES treatment_type(treatment_type_id),
 required_chair_kind VARCHAR(40) CHECK (btrim(required_chair_kind) <> ''),
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 expires_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL CHECK(status IN ('HOLD','CONFIRMED','EXPIRED','RELEASED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(start_at<end_at),
 CHECK(status <> 'HOLD' OR expires_at IS NOT NULL),
 CONSTRAINT slot_claim_dentist_time_excl
  EXCLUDE USING gist (dentist_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&)
  WHERE (status IN ('HOLD','CONFIRMED')) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE deposit_payment (
 deposit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 claim_id BIGINT NOT NULL UNIQUE REFERENCES slot_claim(claim_id),
 amount NUMERIC(12,2) NOT NULL DEFAULT 50.00 CHECK(amount>=0),
 status VARCHAR(30) NOT NULL CHECK(status IN ('PENDING','PAID','FAILED')),
 payment_token VARCHAR(100) UNIQUE,
