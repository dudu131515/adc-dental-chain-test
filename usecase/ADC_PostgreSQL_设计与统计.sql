-- 已知付费差额的资金事件应引用同一主单的 adjustment_id，由服务在同一事务验证。
-- 服务事务锁定 source_payment_id 对应的已成功原缴费，核对主单一致与事件类型为 PAYMENT。
-- 按原缴费汇总已成功及待处理退款，计入新退款后总额不得超过原缴费金额。
-- 应履约按当前 claim_id 的本地开始日期归期，剔除诊所原因取消与历史替换时段。
-- 使用方传入统计截点 as_of，筛选 slot_end_at<=as_of 后以同一应履约集合计算实际接诊率和患者取消率。
-- 诊所取消单列。截至统计截点，状态仍为 CONFIRMED 或 CHECKED_IN 的已结束时段记为未处理。
-- 统计查询以 NULLIF(应履约数,0) 作分母；视图输出当前状态与最终时段。
CREATE VIEW appointment_reporting_fact AS
SELECT a.appointment_id, c.clinic_id, c.dentist_id,
       (c.start_at AT TIME ZONE 'Asia/Shanghai')::date AS service_date,
       c.end_at AS slot_end_at,
       a.is_attended, a.status,
       COALESCE(a.status='CANCELLED' AND ch.cancel_party='PATIENT',false) AS patient_cancelled,
       COALESCE(a.status='CANCELLED' AND ch.cancel_party='CLINIC',false) AS clinic_cancelled
FROM appointment a
JOIN slot_claim c ON c.claim_id=a.claim_id
JOIN deposit_payment d ON d.deposit_id=a.deposit_id AND d.status='PAID'
LEFT JOIN LATERAL (
 SELECT change.cancel_party FROM appointment_change change
 WHERE change.appointment_id=a.appointment_id AND change.change_type='CANCEL'
 ORDER BY change.changed_at DESC, change.id DESC LIMIT 1
) ch ON true;

CREATE VIEW invoice_reporting_fact AS
SELECT i.invoice_id, i.visit_id,
       (v.ended_at AT TIME ZONE 'Asia/Shanghai')::date AS ended_local_date,
       i.original_total + COALESCE(a.adjustments,0) AS accrued_amount,
       COALESCE(p.payment,0) AS received_amount,
       COALESCE(p.refunds,0) AS refunded_amount,
       GREATEST(i.original_total + COALESCE(a.adjustments,0)
                - COALESCE(p.payment,0) + COALESCE(p.refunds,0),0) AS outstanding_amount,
       GREATEST(COALESCE(p.payment,0) - COALESCE(p.refunds,0)
                - i.original_total - COALESCE(a.adjustments,0),0) AS refund_due
FROM invoice i JOIN visit v ON v.visit_id=i.visit_id
LEFT JOIN LATERAL (
 SELECT SUM(signed_amount) AS adjustments FROM invoice_adjustment WHERE invoice_id=i.invoice_id
) a ON true
LEFT JOIN LATERAL (
 SELECT SUM(amount) FILTER(WHERE payment_kind='PAYMENT') AS payment,
        SUM(amount) FILTER(WHERE payment_kind='REFUND') AS refunds
 FROM invoice_payment WHERE invoice_id=i.invoice_id AND status='SUCCEEDED'
) p ON true;

CREATE VIEW expense_reporting_fact AS
SELECT e.expense_id,e.clinic_id,e.period_id,e.scope,e.dentist_id,e.amount,
       CASE WHEN e.scope='SHARED' THEN COALESCE(a.allocated,0) ELSE e.amount END AS attributed,
       CASE WHEN e.scope='SHARED' THEN e.amount-COALESCE(a.allocated,0) ELSE 0 END AS unallocated
FROM operating_expense e
LEFT JOIN LATERAL (
 SELECT SUM(allocated_amount) AS allocated FROM expense_allocation WHERE expense_id=e.expense_id
) a ON true;

-- 当前版本、原版与差额的同列对照，供确认状态及绩效报告筛选。
CREATE VIEW company_performance_revision_fact AS
SELECT p.period_id,p.perf_year,p.perf_quarter,
       r.revision_id,r.revision_no,r.source_adjustment_id,r.confirmed_by,r.confirmed_at,
       c.calculated_at,c.revenue,c.material_cost,c.operating_cost,c.net_profit,c.incentive_fund,
       o.revenue AS original_revenue,o.material_cost AS original_material_cost,
       o.operating_cost AS original_operating_cost,o.net_profit AS original_net_profit,
       o.incentive_fund AS original_incentive_fund,
       c.revenue-o.revenue AS revenue_delta,c.material_cost-o.material_cost AS material_cost_delta,
       c.operating_cost-o.operating_cost AS operating_cost_delta,c.net_profit-o.net_profit AS net_profit_delta,
       c.incentive_fund-o.incentive_fund AS incentive_fund_delta
FROM company_performance c
JOIN performance_revision r ON (r.period_id,r.revision_no)=(c.period_id,c.revision_no)
JOIN performance_period p ON p.period_id=c.period_id
LEFT JOIN company_performance o ON o.period_id=c.period_id AND o.revision_no=1;
