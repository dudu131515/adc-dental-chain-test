CREATE TABLE treatment_type (
 treatment_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 treatment_code VARCHAR(50) NOT NULL UNIQUE,
 treatment_name VARCHAR(160) NOT NULL, standard_unit VARCHAR(50) NOT NULL,
 required_qualification_id BIGINT REFERENCES qualification(qualification_id),
 active BOOLEAN NOT NULL DEFAULT TRUE,
